import { chromium } from 'playwright';
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join, basename } from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const threeDir = dirname(require.resolve('three'));
const html = await readFile(new URL('../index.html', import.meta.url));
const server = createServer((req,res)=>{res.setHeader('Content-Type','text/html; charset=utf-8');res.end(html)});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const url='http://127.0.0.1:'+server.address().port;
let browser;
try{
 browser=await chromium.launch({headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader','--disable-dev-shm-usage']});
 const page=await browser.newPage({viewport:{width:1280,height:720}});
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.route(/https:\/\/(?:cdn\.jsdelivr\.net|unpkg\.com)\/.*three@0\.180\.0\/build\/.*\.js$/,async route=>{
  const name=basename(new URL(route.request().url()).pathname);
  if(!['three.module.js','three.core.js'].includes(name))return route.abort();
  await route.fulfill({body:await readFile(join(threeDir,name)),contentType:'text/javascript',headers:{'access-control-allow-origin':'*'}});
 });
 const button=(label)=>page.locator('#ne2nav').getByRole('button',{name:label,exact:true});
 await page.goto(url);
 await page.locator('#ne2boot').waitFor({state:'hidden',timeout:60000});
 await page.waitForTimeout(400);
 assert.match(await page.locator('#ne2room').innerText(),/01/);
 await page.screenshot({path:'nereid-interior.png'});
 await button('USE / E').click();
 await button('MAN HELM').click();
 await button('HDG +').click();
 await button('THR 0/4').click();
 await page.waitForTimeout(1200);
 assert.ok(Number(await page.locator('#ne2speed').innerText())>0);
 assert.match(await page.locator('#ne2comp').innerText(),/092/);
 await button('DIVE').click();
 await page.waitForTimeout(500);
 assert.ok(Number(await page.locator('#ne2depth').innerText())>80);
 await button('EXIT').click();
 await button('SONAR').click();
 await button('ACTIVE PING').click();
 await button('TRACK').click();
 await button('EXIT').click();
 await button('ROOM ▸').click();
 await button('ROOM ▸').click();
 await button('USE / E').click();
 await page.waitForTimeout(250);
 assert.match(await page.locator('#ne2room').innerText(),/MANIPULATOR|OPTIC/);
 await button('EXIT').click();
 await page.setViewportSize({width:390,height:844});
 await page.waitForTimeout(250);
 assert.equal(await page.locator('#ne2world').isVisible(),true);
 await page.screenshot({path:'nereid-mobile.png'});
 assert.deepEqual(errors,[]);
 console.log('Browser boot, desktop view, helm, depth, sonar, station navigation and mobile smoke passed.');
}finally{await browser?.close();server.close()}
